import React, { useState } from 'react';
import { Incident } from '../types';
import { X, Copy, Check, Download, FileText, Share2 } from 'lucide-react';

interface PostMortemModalProps {
  incident: Incident | null;
  isOpen: boolean;
  onClose: () => void;
}

export const PostMortemModal: React.FC<PostMortemModalProps> = ({
  incident,
  isOpen,
  onClose
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen || !incident || !incident.postMortemDraft) return null;

  const markdownContent = `# CaseMind Blameless Post-Mortem: ${incident.id}
**Title:** ${incident.title}
**Severity:** ${incident.severity}
**Status:** ${incident.status}
**Service Affected:** ${incident.service}
**Cluster:** ${incident.cluster}
**Incident Commander:** ${incident.assignee.name} (${incident.assignee.role})
**Generated At:** ${incident.postMortemDraft.generatedAt}

---

## 1. Executive Summary
${incident.postMortemDraft.summary}

## 2. Impact & Blast Radius
- **Impacted Users:** ${incident.blastRadius.affectedUsers.toLocaleString()} (${incident.blastRadius.pctTraffic}% total traffic)
- **Primary Region:** ${incident.blastRadius.region}
- **Downstream Services Affected:** ${incident.blastRadius.downstreamServices.join(', ')}
- **Estimated Revenue Exposure:** ${incident.blastRadius.revenueImpactPerHour}

## 3. Root Cause Analysis (Autonomous Grounded Synthesis)
${incident.postMortemDraft.rootCauseAnalysis}

**Cognitive Telemetry Confidence:** ${incident.cognitiveSynthesis.confidenceScore}%
- Root Cause Verification: ${incident.cognitiveSynthesis.confidenceBreakdown.rootCause}%
- Organizational Memory Match: ${incident.evidenceProvenance.memoryMatches.map(m => `${m.incidentId} (${m.similarityScore}% similarity)`).join(', ') || 'N/A'}

## 4. Chronological Incident Timeline
${incident.postMortemDraft.timelineSummary}

## 5. Preventative Action Items & Architectural Remediation
${incident.postMortemDraft.preventionItems.map((item, idx) => `${idx + 1}. ${item} [Status: Open, Owner: SRE-Team]`).join('\n')}

---
*Generated by CaseMind Cognitive Operations Platform · Grounded on telemetry spans and organizational memory.*
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `postmortem-${incident.id.toLowerCase()}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-black/60 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-white rounded-2xl max-w-3xl w-full p-6 shadow-2xl border border-[#dae2fd] space-y-4 max-h-[90vh] overflow-y-auto">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-[#eaedff] pb-3">
          <div className="flex items-center space-x-2">
            <span className="p-1.5 rounded-lg bg-[#eaedff] text-[#3525cd]">
              <FileText className="w-5 h-5 text-[#3525cd]" />
            </span>
            <div>
              <h3 className="text-base font-bold text-[#131b2e]">
                Blameless Post-Mortem Export ({incident.id})
              </h3>
              <p className="text-xs text-[#464555]">
                Production-ready incident report generated from telemetry and organizational memory.
              </p>
            </div>
          </div>

          <button onClick={onClose} className="p-1.5 rounded-lg text-[#777587] hover:bg-[#f2f3ff]">
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Action Bar */}
        <div className="flex items-center justify-between bg-[#faf8ff] p-2.5 rounded-lg border border-[#eaedff]">
          <span className="text-xs font-mono text-[#464555]">
            Format: Standard SRE Markdown (Jira / Confluence / Notion compatible)
          </span>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="flex items-center space-x-1.5 px-3 py-1.5 text-xs font-semibold rounded-md bg-white border border-[#c7c4d8] text-[#131b2e] hover:bg-[#f2f3ff] transition-colors"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-[#059669]" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied to Clipboard' : 'Copy Markdown'}</span>
            </button>

            <button
              onClick={handleDownload}
              className="flex items-center space-x-1.5 px-3 py-1.5 text-xs font-semibold rounded-md bg-[#3525cd] text-white hover:bg-[#4f46e5] transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download .md</span>
            </button>
          </div>
        </div>

        {/* Document Content View */}
        <div className="bg-[#0f172a] rounded-xl p-5 border border-[#283044] text-[#eaedff] font-mono text-xs overflow-x-auto leading-relaxed max-h-[480px]">
          <pre>{markdownContent}</pre>
        </div>

        <div className="flex items-center justify-end space-x-2 pt-2 border-t border-[#eaedff]">
          <button
            onClick={onClose}
            className="px-4 py-2 text-xs font-semibold text-[#131b2e] bg-[#f2f3ff] hover:bg-[#eaedff] rounded-lg"
          >
            Close
          </button>
        </div>
      </div>
    </div>
  );
};
